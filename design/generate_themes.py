"""
Turns realtime_colors_20_themes.css into Kotlin (RealtimeThemes.kt) and prints a contrast
check of the colours the app picks from each theme.

    py design/generate_themes.py

To add a theme: add its block to the CSS file, add a line to THEMES below, run this again,
then add it to the Shop list in EconomyRepository if it should be sold there (themes in
RealtimeThemes.kt show up in Settings and the Shop automatically).
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
CSS = os.path.join(HERE, "realtime_colors_20_themes.css")
OUT = os.path.join(HERE, "..", "app", "src", "main", "java", "com", "habitgame", "ui", "theme", "RealtimeThemes.kt")

# id -> (display name, emoji, description). The order here is the order in the Shop and Settings.
THEMES = {
    "lavender-dream": ("Lavender Dream", "💜", "Light lavender and violet"),
    "midnight-blue": ("Midnight Blue", "🌌", "Dark navy and blue"),
    "forest-mist": ("Forest Mist", "🌿", "Light natural green"),
    "neon-forest": ("Neon Forest", "🍀", "Dark, with neon lime"),
    "sunset-ember": ("Sunset Ember", "🌅", "Light warm orange"),
    "cosmic-purple": ("Cosmic Purple", "🪐", "Dark cosmic violet"),
    "ocean-breeze": ("Ocean Breeze", "🌊", "Light teal and aqua"),
    "deep-ocean": ("Deep Ocean", "🐋", "Dark cyan and deep teal"),
    "rose-quartz": ("Rose Quartz", "🌸", "Light soft pink"),
    "crimson-night": ("Crimson Night", "🍷", "Dark crimson red"),
    "golden-hour": ("Golden Hour", "🌇", "Light gold and amber"),
    "solar-flare": ("Solar Flare", "☀️", "Dark, with gold"),
    "arctic-silver": ("Arctic Silver", "❄️", "Light cool grey"),
    "graphite": ("Graphite", "✏️", "Dark minimal grey"),
    "orchid-bloom": ("Orchid Bloom", "🌺", "Light orchid and magenta"),
    "electric-orchid": ("Electric Orchid", "🎆", "Dark electric magenta"),
    "sandstone": ("Sandstone", "🏜️", "Light earthy neutral"),
    "dark-mocha": ("Dark Mocha", "☕", "Dark coffee brown"),
    "sky-glass": ("Sky Glass", "🌤️", "Light sky blue"),
    "amoled-sky": ("AMOLED Sky", "🌃", "Near-black, with blue"),
}
GROUPS = ["text", "background", "primary", "secondary", "accent"]
STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]


def parse(css):
    themes = {}
    for name, body in re.findall(r':root\[data-theme="([a-z-]+)"\]\s*\{(.*?)\}', css, re.S):
        values = dict(re.findall(r"--([a-z]+-\d+):\s*(#[0-9A-Fa-f]{6})\s*;", body))
        scales = {}
        for g in GROUPS:
            missing = [s for s in STEPS if f"{g}-{s}" not in values]
            assert not missing, f"{name}: {g} is missing shades {missing}"
            scales[g] = [values[f"{g}-{s}"].upper() for s in STEPS]
        themes[name] = scales
    return themes


def lum(hex_):
    def ch(c):
        c = int(c, 16) / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = hex_[1:3], hex_[3:5], hex_[5:7]
    return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b)


def contrast(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def pick(scale, bg, start):
    """Same rule as ThemeShades.toPalette(): the first shade from [start] onwards that reads 4.5:1 on [bg]."""
    for i in range(STEPS.index(start), len(STEPS)):
        if contrast(scale[i], bg) >= 4.5:
            return scale[i]
    return scale[-1]


def main():
    css = open(CSS, encoding="utf-8").read()
    themes = parse(css)
    assert list(themes) == list(THEMES), f"CSS themes {list(themes)} don't match THEMES"

    lines = [
        "// Generated by design/generate_themes.py from design/realtime_colors_20_themes.css. Don't edit by hand:",
        "// change the CSS (or the names in the script) and run the script again.",
        "package com.habitgame.ui.theme",
        "",
        "/** The 20 Realtime Colors themes, with all 11 shades of each of their five palettes. */",
        "internal val RealtimeThemes: List<ThemeShades> = listOf(",
    ]
    print(f"{'theme':16} {'dark':5} {'text/bg':>8} {'dim/bg':>7} {'dim/card':>8} {'primary/bg':>10} {'onPrimary':>9}")
    for tid, scales in themes.items():
        name, emoji, desc = THEMES[tid]
        dark = lum(scales["text"][0]) < lum(scales["text"][-1])
        bg = scales["background"][0]
        card = scales["background"][1]
        primary = pick(scales["primary"], bg, 500 if dark else 600)
        on_primary = max(("#111111", "#FFFFFF"), key=lambda c: contrast(c, primary))
        dim = pick(scales["text"], card, 600)
        print(f"{tid:16} {str(dark):5} {contrast(scales['text'][9], bg):8.1f} {contrast(dim, bg):7.1f} "
              f"{contrast(dim, card):8.1f} {contrast(primary, bg):10.1f} {contrast(on_primary, primary):9.1f}")

        lines.append("    ThemeShades(")
        lines.append(f'        id = "{tid}", name = "{name}", emoji = "{emoji}", description = "{desc}", dark = {str(dark).lower()},')
        for g in GROUPS:
            hexes = ", ".join("0xFF" + h[1:] for h in scales[g])
            lines.append(f"        {g} = shades({hexes}),")
        lines[-1] = lines[-1].rstrip(",")
        lines.append("    ),")
    lines[-1] = "    )"
    lines.append(")")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(f"\nWrote {len(themes)} themes to {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
